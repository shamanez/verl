#!/usr/bin/env python3
"""Generate the step-100 benchmark table for the RLVR v3 section from the eval
harness output, and splice it into the .tex between its BEGIN/END markers.

The numbers are read straight from the per-benchmark train.log files that
ood_eval.sh writes, so the table cannot drift from the harness by a
transcription error. Benchmarks with no result yet render as "n/a" and are
excluded from the average, which lets the table be regenerated while the matrix
is still running.

Usage:
  python3 make_v3_bench_table.py --acc acc.tsv --tex <path to v3 .tex>

acc.tsv is "<tag>/<bench><TAB><value>" per line, as produced on the eval box by:
  for t in base commeff100 dense100; do for b in <benches>; do ... done; done
"""
import argparse
import re

BENCHES = [
    ("math500", "MATH500"),
    ("gsm8k", "GSM8K"),
    ("minerva", "Minerva"),
    ("olympiad", "OlympiadBench"),
    ("mmlu_stem", "MMLU-STEM"),
    ("amc23", "AMC23"),
    ("aime24", "AIME24"),
    ("aime25", "AIME25"),
    ("aime26", "AIME26"),
    ("hmmt25", "HMMT25"),
]
BEGIN = "% BEGIN-BENCH-TABLE"
END = "% END-BENCH-TABLE"


def load(path):
    acc = {}
    for line in open(path):
        line = line.strip()
        if not line or "\t" not in line:
            continue
        key, val = line.split("\t", 1)
        try:
            acc[key.strip()] = float(val)
        except ValueError:
            pass
    return acc


def fmt(v):
    return "n/a" if v is None else f"{v:.3f}"


def build(acc):
    rows, gaps = [], []
    sums = {"base": [], "dense100": [], "commeff100": []}
    for i, (key, label) in enumerate(BENCHES):
        b = acc.get(f"base/{key}")
        d = acc.get(f"dense100/{key}")
        c = acc.get(f"commeff100/{key}")
        for name, v in (("base", b), ("dense100", d), ("commeff100", c)):
            if v is not None:
                sums[name].append(v)
        if d is not None and c is not None:
            gap = c - d
            gaps.append(gap)
            colour = "deltapos" if gap > 0 else ("deltaneg" if gap < 0 else None)
            gtxt = (f"\\textcolor{{{colour}}}{{${gap:+.3f}$}}" if colour else "$0.000$")
            dtxt = f"\\textbf{{{d:.3f}}}" if d >= c else f"{d:.3f}"
            ctxt = f"\\textbf{{{c:.3f}}}" if c >= d else f"{c:.3f}"
        else:
            gtxt, dtxt, ctxt = "n/a", fmt(d), fmt(c)
        shade = "\\rowcolor{rowgray}\n" if i % 2 == 1 else ""
        rows.append(f"{shade}{label:13s} & {fmt(b)} & {dtxt} & {ctxt} & {gtxt} \\\\")

    avg = {k: (sum(v) / len(v) if v else None) for k, v in sums.items()}
    if avg["dense100"] is not None and avg["commeff100"] is not None:
        ag = avg["commeff100"] - avg["dense100"]
        # a gap that rounds to 0.000 must not render as a signed colored zero
        col = None if round(abs(ag), 3) == 0 else ("deltapos" if ag > 0 else "deltaneg")
        atxt = f"\\textcolor{{{col}}}{{${ag:+.3f}$}}" if col else "$0.000$"
        ad = (f"\\textbf{{{avg['dense100']:.3f}}}" if avg["dense100"] >= avg["commeff100"]
              else f"{avg['dense100']:.3f}")
        ac = (f"\\textbf{{{avg['commeff100']:.3f}}}" if avg["commeff100"] >= avg["dense100"]
              else f"{avg['commeff100']:.3f}")
    else:
        atxt, ad, ac = "n/a", fmt(avg["dense100"]), fmt(avg["commeff100"])

    n_c = sum(1 for g in gaps if g > 0)
    n_d = sum(1 for g in gaps if g < 0)
    caption = (
        "\\small Capability at step $100$, dense against $95\\%$ compressed, "
        "the matched point at which both arms are healthy. Both checkpoints are "
        "merged to plain dense models and scored with one identical harness: "
        "greedy accuracy at $1$ for MATH500, GSM8K, Minerva, OlympiadBench and "
        "MMLU-STEM; average of $8$ samples at temperature $0.7$ for AMC23, "
        "AIME24/25/26 and HMMT25. $\\Delta$ is compressed minus dense. "
    )
    # Never emit a summary sentence built from missing cells: a "nan" or a "0 of
    # 0" reads as a measured result rather than as absent data.
    if gaps:
        mag = sum(abs(g) for g in gaps) / len(gaps)
        caption += (
            f"The mean absolute gap is ${mag:.3f}$, compressed is ahead on {n_c} "
            f"of {len(gaps)} benchmarks and dense on {n_d}, and the direction "
            "alternates across the suite, which is the signature of run-to-run "
            "noise rather than a compression penalty. "
        )
    else:
        caption += "Comparison columns are pending the evaluation matrix. "
    caption += (
        "Compare Table~\\ref{tab:rlvr-val}: one hundred steps later this parity "
        "is gone."
    )
    body = "\n".join(rows)
    return f"""{BEGIN} (generated by make_v3_bench_table.py; do not edit by hand)
\\begin{{table}}[t]
\\centering
\\scriptsize
\\setlength{{\\tabcolsep}}{{4.5pt}}
\\renewcommand{{\\arraystretch}}{{1.12}}
\\caption{{{caption}}}
\\label{{tab:rlvr-step100}}
\\begin{{tabular}}{{l c c c c}}
\\toprule
\\rowcolor{{headerblue!15}}
\\textbf{{Benchmark}} & \\textbf{{Base}} & \\textbf{{Dense @100}} &
\\textbf{{Compressed @100}} & \\textbf{{$\\Delta$}} \\\\
\\midrule
{body}
\\midrule
\\rowcolor{{ourrow}}
Average       & {fmt(avg['base'])} & {ad} & {ac} & {atxt} \\\\
\\bottomrule
\\end{{tabular}}
\\end{{table}}
{END}"""


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--acc", required=True)
    ap.add_argument("--tex", required=True)
    a = ap.parse_args()
    table = build(load(a.acc))
    src = open(a.tex).read()
    pat = re.compile(re.escape(BEGIN) + r".*?" + re.escape(END), re.S)
    if not pat.search(src):
        raise SystemExit(f"markers {BEGIN} .. {END} not found in {a.tex}")
    open(a.tex, "w").write(pat.sub(lambda _: table, src))
    print(f"spliced benchmark table into {a.tex}")


if __name__ == "__main__":
    main()
